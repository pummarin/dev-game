/** Central catalog for item display, categories, stacking, and data-driven use effects. */
export type ItemCategory = 'consumable' | 'equipment' | 'material';
export type ItemRarity = 'common' | 'uncommon' | 'rare' | 'epic' | 'legendary';
export type EquipmentSlot = 'head' | 'weapon' | 'necklace' | 'ring1' | 'ring2' | 'armor' | 'offhand' | 'gloves' | 'boots';
export type EquipmentItemSlot = Exclude<EquipmentSlot, 'ring1' | 'ring2'> | 'ring';
export type EquipmentAppearanceLayer = 'armor' | 'shield' | 'weapon';
export type EquipmentBonuses = Partial<{
  maxHp: number;
  maxMp: number;
  physicalAttack: number;
  magicAttack: number;
  physicalDefense: number;
  criticalChance: number;
  criticalDamage: number;
  attackSpeed: number;
  movementSpeed: number;
}>;
export type ItemUseEffect = { type: 'restoreHp' | 'restoreMp'; amount: number };
type ItemBaseDefinition = {
  id: string;
  name: string;
  description: string;
  color: number;
  category: ItemCategory;
  rarity: ItemRarity;
  iconFrame: number;
  /** Base vendor prices before rarity scaling; currency is gold. */
  buyPrice: number;
  sellPrice: number;
};
export type MaterialItemDefinition = ItemBaseDefinition & {
  category: 'material';
  useEffect?: never;
  equipmentSlot?: never;
  statBonuses?: never;
};
export type ConsumableItemDefinition = ItemBaseDefinition & {
  category: 'consumable';
  useEffect: ItemUseEffect;
  equipmentSlot?: never;
  statBonuses?: never;
};
export type EquipmentItemDefinition = ItemBaseDefinition & {
  category: 'equipment';
  useEffect?: never;
  equipmentSlot: EquipmentItemSlot;
  /** Fixed, authored primary stats only. Rarity affixes are rolled separately. */
  statBonuses: EquipmentBonuses;
  /** Reserved mapping for future frame-aligned equipment sprite layers. */
  appearanceLayer?: EquipmentAppearanceLayer;
};
export type ItemDefinition = MaterialItemDefinition | ConsumableItemDefinition | EquipmentItemDefinition;

