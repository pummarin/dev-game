export function getItemPrices(itemId: string) {
  const item = getItemDefinition(itemId);
  if (!item) return undefined;
  const multiplier = item.category === 'equipment' ? EQUIPMENT_RARITY_MULTIPLIERS[getItemRarity(itemId)] : 1;
  return {
    buyPrice: Math.round(item.buyPrice * multiplier),
    sellPrice: Math.round(item.sellPrice * multiplier),
  };
}
