/** Random rarity is rolled for equipment drops only. These are percentage weights. */
export const EQUIPMENT_RARITY_WEIGHTS: Record<ItemRarity, number> = {
  common: 60, uncommon: 25, rare: 10, epic: 4, legendary: 1,
};
export const EQUIPMENT_RARITY_MULTIPLIERS: Record<ItemRarity, number> = {
  common: 1, uncommon: 1.25, rare: 1.5, epic: 1.8, legendary: 2.2,
};

const INSTANCE_SEPARATOR = '::';
export function makeItemInstanceId(itemId: string, rarity: ItemRarity) {
  const item = ITEMS[itemId];
  const baseStats = item?.statBonuses ?? {};
  const extraCount: Record<ItemRarity, number> = { common: 0, uncommon: 1, rare: 2, epic: 3, legendary: 4 };
  const ranges: Partial<Record<ItemRarity, [number, number]>> = {
    uncommon: [1, 2], rare: [2, 4], epic: [3, 6], legendary: [5, 8],
  };
  const candidates = (Object.keys(EQUIPMENT_STAT_LABELS) as Array<keyof EquipmentBonuses>)
    .filter((stat) => baseStats[stat] === undefined);
  const extras: string[] = [];
  const [min = 0, max = 0] = ranges[rarity] ?? [];
  for (let index = 0; index < extraCount[rarity] && candidates.length > 0; index += 1) {
    const candidateIndex = Math.floor(Math.random() * candidates.length);
    const stat = candidates.splice(candidateIndex, 1)[0];
    const value = min + Math.floor(Math.random() * (max - min + 1));
    extras.push(`${stat}=${value}`);
  }
  return `${itemId}${INSTANCE_SEPARATOR}${rarity}${INSTANCE_SEPARATOR}${extras.join(',')}`;
}
export function getBaseItemId(itemInstanceId: string) {
  return itemInstanceId.split(INSTANCE_SEPARATOR, 1)[0];
}
export function getItemRarity(itemInstanceId: string): ItemRarity {
  const encodedRarity = itemInstanceId.split(INSTANCE_SEPARATOR)[1] as ItemRarity | undefined;
  return encodedRarity && encodedRarity in EQUIPMENT_RARITY_MULTIPLIERS
    ? encodedRarity
    : ITEMS[getBaseItemId(itemInstanceId)]?.rarity ?? 'common';
}
export function rollEquipmentRarity(random = Math.random()): ItemRarity {
  let roll = Math.max(0, Math.min(0.999999999, random)) * 100;
  for (const rarity of ['common', 'uncommon', 'rare', 'epic', 'legendary'] as const) {
    roll -= EQUIPMENT_RARITY_WEIGHTS[rarity];
    if (roll < 0) return rarity;
  }
  return 'common';
}
export function getItemStatBonuses(itemInstanceId: string): EquipmentBonuses | undefined {
  const item = ITEMS[getBaseItemId(itemInstanceId)];
  if (!item?.statBonuses) return undefined;
  const randomBonuses: EquipmentBonuses = {};
  const encodedExtras = itemInstanceId.split(INSTANCE_SEPARATOR)[2] ?? '';
  encodedExtras.split(',').filter(Boolean).forEach((entry) => {
    const [stat, value] = entry.split('=');
    if (stat in EQUIPMENT_STAT_LABELS && Number.isFinite(Number(value))) {
      const key = stat as keyof EquipmentBonuses;
      randomBonuses[key] = (randomBonuses[key] ?? 0) + Number(value);
    }
  });
  // Keep each item's authored base stats first, then append its rolled bonus stats.
  // This makes the registry the single source of truth for display ordering.
  const bonuses: EquipmentBonuses = {};
  const rarity = getItemRarity(itemInstanceId);
  const multiplier = EQUIPMENT_RARITY_MULTIPLIERS[rarity];
  (Object.keys(item.statBonuses) as Array<keyof EquipmentBonuses>).forEach((key) => {
    const baseValue = item.statBonuses?.[key] ?? 0;
    // Equipment stats are whole numbers; standard half-up rounding keeps the UI and totals consistent.
    bonuses[key] = Math.round(baseValue * multiplier);
  });
  (Object.keys(randomBonuses) as Array<keyof EquipmentBonuses>).forEach((key) => {
    bonuses[key] = (bonuses[key] ?? 0) + (randomBonuses[key] ?? 0);
  });
  return bonuses;
}

